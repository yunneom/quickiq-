export type MuralStyleId = 'plaster' | 'school' | 'brick' | 'night' | 'blackboard';

export interface MuralStyle {
  id: MuralStyleId;
  /** Korean label for /admin/media. */
  label: string;
  /** Surface half of the generation prompt (the framing half is shared). */
  surface: string;
  /** Paint colour for headline, options and figures. */
  ink: string;
  /** Outline colour inside recoloured figures (cube edges). */
  outline: string;
  /** Marker colour for the "?" tile. */
  accent: string;
  blend: 'multiply' | 'screen';
  /** Top of the painted block, in FOOTAGE space (1512×2688). */
  textTop: number;
  /**
   * Where the painted block must stop — roughly where the person's head
   * starts in this style's shots. Paint below this and the question ends
   * up written across the subject instead of the wall.
   */
  blockBottom: number;
}

