/**
 * The framing half of the prompt — identical for every style so the pool
 * stays visually coherent. The negatives are load-bearing: without them
 * the model writes its own (garbled) text on the wall, and it has been
 * observed inventing a phone status bar and clock along the bottom edge.
 */
const FRAMING = [
  'Vertical 9:16 smartphone photo, documentary style, camera square-on and parallel to the',
  'flat surface with no perspective distortion. Shot from behind the subject at chest',
  'height. One person seen strictly FROM BEHIND — back of the head and shoulders only,',
  'face completely not visible — standing and looking up at the surface. The person is',
  'small, in the bottom third of the frame, slightly off-centre.',
  'CRITICAL: the surface must be completely BLANK and EMPTY — no text, no letters, no',
  'numbers, no writing, no chalk marks, no posters, no signs, no graffiti, no drawings.',
  'No phone UI, no status bar, no navigation bar, no timestamp, no watermark, no border.',
  'Photorealistic. No text anywhere in the image.',
].join(' ');

export function muralPrompt(style: MuralStyle): string {
  return `${FRAMING} ${style.surface}`;
}

// ---------------------------------------------------------------------------
// Generation (Gemini)
