/**
 * Tried in order. The preview model produces the better wall but is not
 * guaranteed to be enabled on every key, so the flash model backs it up —
 * a pool that fills with slightly plainer walls beats a pool that stays
 * empty.
 */
const IMAGE_MODELS = ['gemini-3-pro-image', 'gemini-2.5-flash-image'];
const API_ROOT = 'https://generativelanguage.googleapis.com/v1beta/models';

export type GenerateResult =
  | { ok: true; image: Buffer; model: string }
  | { ok: false; reason: string };

/** Generate one wall photo for a style. Returns raw model output bytes. */
export async function generateMuralImage(args: {
  style: MuralStyle;
  apiKey: string;
  deadlineAt?: number;
}): Promise<GenerateResult> {
  const body = JSON.stringify({
    contents: [{ parts: [{ text: muralPrompt(args.style) }] }],
    generationConfig: {
      responseModalities: ['IMAGE'],
      imageConfig: { aspectRatio: '9:16' },
    },
  });

  const notes: string[] = [];
  for (const model of IMAGE_MODELS) {
    if (args.deadlineAt && Date.now() > args.deadlineAt) {
      return { ok: false, reason: `deadline_exceeded after: ${notes.join('; ')}` };
    }
    const budget = args.deadlineAt
      ? Math.min(120_000, Math.max(5_000, args.deadlineAt - Date.now()))
      : 120_000;
    try {
      const res = await fetch(`${API_ROOT}/${model}:generateContent`, {
        method: 'POST',
        headers: { 'x-goog-api-key': args.apiKey, 'Content-Type': 'application/json' },
        body,
        cache: 'no-store',
        signal: AbortSignal.timeout(budget),
      });
      const raw = (await res.json().catch(() => ({}))) as {
        candidates?: { content?: { parts?: { inlineData?: { data?: string } }[] } }[];
        error?: { message?: string; status?: string };
      };
      if (!res.ok || raw.error) {
        notes.push(`${model}: ${raw.error?.message ?? `http_${res.status}`}`);
        continue;
      }
      const part = raw.candidates?.[0]?.content?.parts?.find((p) => p.inlineData?.data);
      if (!part?.inlineData?.data) {
        notes.push(`${model}: no_image_in_response`);
        continue;
      }
      return { ok: true, image: Buffer.from(part.inlineData.data, 'base64'), model };
    } catch (err) {
      notes.push(`${model}: ${err instanceof Error ? err.message : 'fetch_failed'}`);
    }
  }
  return { ok: false, reason: notes.join('; ') || 'no_model_available' };
}

/** Normalise model output to the stored footage size. */
export async function normalizeMuralImage(image: Buffer): Promise<Buffer> {
  return sharp(image)
    .resize(FOOTAGE_W, FOOTAGE_H, { fit: 'cover', position: 'centre' })
    .jpeg({ quality: 88 })
    .toBuffer();
}

