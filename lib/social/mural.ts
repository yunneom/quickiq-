/**
 * "Question painted on a wall" posts.
 *
 * The format that actually travels on Instagram is not a card floating
 * over a video — it is a photograph of a real wall with the puzzle
 * painted onto it and a person standing there reading it. This module
 * produces exactly that:
 *
 *   1. the WALL is generated once per pool entry by Gemini (photoreal,
 *      person seen strictly from behind, surface left deliberately blank)
 *      and parked in our own bucket — see murals.ts
 *   2. the QUESTION is drawn here as plain SVG and composited onto the
 *      wall with a blend mode, so the wall's own texture, shadows and
 *      lighting fall across the letters. `multiply` reads as dark paint
 *      soaking into a light wall, `screen` as whitewash or chalk.
 *
 * The text is never generated by the image model. Image models garble
 * letters and digits, and a garbled digit in a maths puzzle is a wrong
 * answer shipped to the audience — so the model only ever draws the
 * empty wall, and every glyph on it comes from our own renderer.
 */

import sharp from 'sharp';
