const esc = (s: string) =>
  s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

/**
 * Rough advance width in em. Hangul and CJK are full-width; Latin at
 * Pretendard's proportions averages a bit over half an em. Two classes
 * is crude but it is the difference between a Korean line and an English
 * line of the same character count differing by ~2× — which a plain
 * character budget gets badly wrong.
 */
function textWidthEm(text: string): number {
  let em = 0;
  for (const ch of text) em += /[ᄀ-ᇿ　-鿿가-힯＀-｠]/.test(ch) ? 1 : 0.56;
  return em;
}

/**
 * Greedy wrap to a maximum line width, measured in em.
 *
 * Breaking on spaces alone is not enough here: Korean routinely runs
 * long stretches with no space at all, and a single over-long token
 * would then sit on one line and run straight off both edges of the
 * wall. Anything wider than the box is therefore also broken between
 * characters, which is the normal line-breaking behaviour for Hangul
 * anyway.
 */
function wrapToWidth(text: string, maxEm: number): string[] {
  const lines: string[] = [];
  let line = '';

  const pushLine = () => {
    if (line) lines.push(line);
    line = '';
  };

  for (const word of text.split(/\s+/).filter(Boolean)) {
    const candidate = line ? `${line} ${word}` : word;
    if (textWidthEm(candidate) <= maxEm) {
      line = candidate;
      continue;
    }
    pushLine();
    if (textWidthEm(word) <= maxEm) {
      line = word;
      continue;
    }
    // Token wider than the whole box — break it between characters.
    for (const ch of word) {
      if (textWidthEm(line + ch) > maxEm && line) pushLine();
      line += ch;
    }
  }
  pushLine();
  return lines;
}

/**
 * Fit the whole question into the headline box by shrinking the type
 * until it fits — never by dropping words.
 *
 * The first cut of this truncated at three lines, which silently ate the
 * tail of every long prompt ("…One is MIRRORED. Which" — the "one is
 * it?" simply gone). A half-question is a broken post, so the only
 * variable allowed to give here is the font size; at the floor the text
 * wraps to as many lines as it needs and stays complete.
 */
export function fitHeadline(
  text: string,
  opts: { boxWidth: number; maxLines?: number } = { boxWidth: 1180 },
): { lines: string[]; size: number } {
  const maxLines = opts.maxLines ?? 4;
  const sizes = [100, 90, 80, 72, 64, 56];
  for (const size of sizes) {
    const lines = wrapToWidth(text, opts.boxWidth / size);
    if (lines.length <= maxLines) return { lines, size };
  }
  const size = sizes[sizes.length - 1];
  return { lines: wrapToWidth(text, opts.boxWidth / size), size };
}

/** Strip the outer <svg> wrapper so a figure can be nested in a <g>. */
function figureBody(svg: string): { body: string; vbW: number; vbH: number } | null {
  const vb = /viewBox="0 0 ([\d.]+) ([\d.]+)"/.exec(svg);
  const inner = /<svg[^>]*>([\s\S]*)<\/svg>/.exec(svg);
  if (!vb || !inner) return null;
  return { body: inner[1], vbW: Number(vb[1]), vbH: Number(vb[2]) };
}

/**
 * Whether a post can be painted onto a wall at all.
 *
 * The mural renderer is plain SVG, so it can carry the two shapes a wall
 * actually needs: a text question, or a self-contained `figure` (every
 * shape puzzle). The remaining scene kinds — road, sequence, bars — are
 * satori JSX components whose content IS the question (the numbers in a
 * sequence, the bars in a rate puzzle); painting only their prompt would
 * ship a post with the question missing. Those keep the card treatment.
 */
export function muralEligible(card: Pick<IgCard, 'scene'>): boolean {
  return !card.scene || card.scene.kind === 'figure';
}

/** The figure a card carries, if it carries one this renderer can paint. */
export function cardFigureSvg(card: Pick<IgCard, 'scene'>): string | undefined {
  return card.scene?.kind === 'figure' ? card.scene.svg : undefined;
}

/**
 * True when the options are pointers INTO the figure ("Shape A", "Shape
 * B") rather than answers in their own right ("13", "intermittent").
 *
 * The rotation and mirror families draw lettered tiles inside the figure
 * itself, so painting a second A–D list beneath it is noise. The numeric
 * families (squares, triangles, lines, cubes) carry their answers only
 * in the option list, and dropping it would ship a puzzle with nothing
 * to choose from — so the fallback when this is unsure must be to DRAW
 * the list, which is what returning false does.
 */
export function optionsAreFigureRefs(options: readonly { text: string }[]): boolean {
  return (
    options.length > 0 &&
    options.every((o) => /^\s*(shape|figure|option)\s+[A-D]\s*$/i.test(o.text))
  );
}

/**
 * The whole painted layer, in FOOTAGE space. Transparent everywhere the
 * paint is not — the caller composites it with the style's blend mode.
 */
export function muralOverlaySvg(args: {
  style: MuralStyle;
  card: Pick<IgCard, 'prompt' | 'options'>;
  /** Shape-puzzle figure, still in its authored white-on-transparent form. */
  figureSvg?: string;
  figureAspect?: number;
  handle?: string;
}): string {
  const { style, card } = args;
  const W = FOOTAGE_W;
  const cx = W / 2;
  const ink = style.ink;
  const top = style.textTop;

  const { lines: headline, size: headSize } = fitHeadline(card.prompt, {
    boxWidth: W - 260,
  });
  const headLead = Math.round(headSize * 1.22);
  const headBottom = top + headline.length * headLead;

  const heading = headline
    .map(
      (line, i) =>
        `<text x="${cx}" y="${top + (i + 1) * headLead}" text-anchor="middle" ` +
        `font-family="Pretendard, Noto Sans KR, sans-serif" font-weight="800" ` +
        `font-size="${headSize}" letter-spacing="-3" fill="${ink}">${esc(line)}</text>`,
    )
    .join('');

  const ruleY = headBottom + 34;
  const rule =
    `<path d="M ${cx - 280} ${ruleY} L ${cx + 280} ${ruleY - 6}" stroke="${ink}" ` +
    `stroke-width="11" stroke-linecap="round"/>`;

  // A running cursor, not fixed offsets: the block's height varies with
  // the headline's line count and with whether a figure is present, and
  // anything placed at a constant y (the handle, most visibly) ends up
  // drawn straight through the figure on the taller layouts.
  let cursor = ruleY;
  let bodyBlock = '';

  const fig = args.figureSvg ? figureBody(args.figureSvg) : null;
  const opts = card.options.slice(0, 4);
  const drawOptions = !fig || !optionsAreFigureRefs(opts);
  const optionRows = drawOptions ? Math.ceil(opts.length / 2) : 0;
  const OPTION_ROW_H = 190;
  const HANDLE_GAP = 90;

  if (fig) {
    const recolored = recolorFigureSvg(
      `<svg viewBox="0 0 ${fig.vbW} ${fig.vbH}">${fig.body}</svg>`,
      { ink, accent: style.accent, outline: style.outline },
    );
    const inner = figureBody(recolored)!;
    const y = cursor + 70;
    // Fit the figure to whatever wall is actually left after the option
    // rows and the handle have taken their share — scaling on width
    // alone runs the block down over the person's head on the shots
    // where the empty wall is short.
    const reserved = optionRows * OPTION_ROW_H + (drawOptions ? 74 : 0) + HANDLE_GAP;
    const availH = Math.max(220, style.blockBottom - y - reserved);
    const scale = Math.min((W - 340) / inner.vbW, availH / inner.vbH);
    const drawW = inner.vbW * scale;
    bodyBlock +=
      `<g transform="translate(${((W - drawW) / 2).toFixed(1)} ${y}) scale(${scale.toFixed(4)})">` +
      `${inner.body}</g>`;
    cursor = y + inner.vbH * scale;
  }

  if (drawOptions) {
    const letters = ['A', 'B', 'C', 'D'];
    const rowTop = cursor + (fig ? 74 : 96);
    const rows = optionRows;
    const colX = [cx - 380, cx + 60];
    bodyBlock += opts
      .map((opt, i) => {
        const x = colX[i % 2];
        const y = rowTop + Math.floor(i / 2) * OPTION_ROW_H;
        return (
          `<circle cx="${x + 48}" cy="${y + 38}" r="46" fill="none" stroke="${ink}" stroke-width="8"/>` +
          `<text x="${x + 48}" y="${y + 60}" text-anchor="middle" ` +
          `font-family="Pretendard, Noto Sans KR, sans-serif" font-weight="800" font-size="52" ` +
          `fill="${ink}">${letters[i]}</text>` +
          `<text x="${x + 122}" y="${y + 60}" font-family="Pretendard, Noto Sans KR, sans-serif" ` +
          `font-weight="700" font-size="52" letter-spacing="-1" fill="${ink}">${esc(opt.text)}</text>`
        );
      })
      .join('');
    cursor = rowTop + rows * OPTION_ROW_H;
  }

  // The handle goes under the block, or nowhere. Clamping it upward (the
  // obvious-looking fix) drags it back INTO the figure, which is exactly
  // the collision it is meant to avoid — so when the wall has run out,
  // the handle is simply dropped.
  const handleY = cursor + HANDLE_GAP;
  const handle =
    args.handle && handleY <= style.blockBottom
      ? `<text x="${cx}" y="${handleY.toFixed(0)}" text-anchor="middle" ` +
      `font-family="Pretendard, Noto Sans KR, sans-serif" font-weight="600" font-size="42" ` +
      `letter-spacing="1.5" fill="${ink}" opacity="0.5">${esc(args.handle)}</text>`
    : '';

  // A hair of rotation keeps it from reading as a digital sticker.
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${FOOTAGE_H}" viewBox="0 0 ${W} ${FOOTAGE_H}">
  <g transform="rotate(-0.4 ${cx} ${top + 200})">${heading}${rule}${bodyBlock}${handle}</g>
</svg>`;
}

/**
 * Paint the question onto a wall photo. The paint is applied at footage
 * resolution BEFORE any Ken Burns crop, so the letters travel with the
 * wall instead of floating over it.
 */
export async function paintMural(args: {
  wall: Buffer;
  style: MuralStyle;
  card: Pick<IgCard, 'prompt' | 'options' | 'scene'>;
  handle?: string;
}): Promise<Buffer> {
  const overlay = Buffer.from(
    muralOverlaySvg({
      style: args.style,
      card: args.card,
      figureSvg: cardFigureSvg(args.card),
      handle: args.handle,
    }),
  );
  return sharp(args.wall)
    .resize(FOOTAGE_W, FOOTAGE_H, { fit: 'cover', position: 'centre' })
    .composite([{ input: overlay, top: 0, left: 0, blend: args.style.blend }])
    .png()
    .toBuffer();
}
